/**
 * The menus of the application menu bar: the familiar ones of VS Code and of the JetBrains IDEs
 * together. Most commands do not exist yet and show as disabled; an item becomes active when the
 * composition root gives its id an action. Shortcuts shown here are the ones the matching feature
 * is planned to use.
 */

export type MenuEntry =
  | { kind: 'separator' }
  | {
      kind: 'item';
      id: string;
      label: string;
      /** Written `Ctrl+Shift+P`; the display adapts it to the operating system. */
      shortcut?: string;
      /** A submenu. Such an item has no action of its own. */
      children?: MenuEntry[];
    };

export interface AppMenu {
  id: string;
  label: string;
  entries: MenuEntry[];
}

const item = (id: string, label: string, shortcut?: string): MenuEntry => ({ kind: 'item', id, label, ...(shortcut ? { shortcut } : {}) });
const sub = (id: string, label: string, children: MenuEntry[]): MenuEntry => ({ kind: 'item', id, label, children });
const sep: MenuEntry = { kind: 'separator' };

